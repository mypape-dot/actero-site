import {readFileSync, readdirSync, mkdirSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

export const schemaURL = new URL('./migrations/0001-empty-staging.sql', import.meta.url);
export function buildSchema() {
  const root = new URL('../', import.meta.url);
  const sources = ['tests/fixtures/local-baseline.sql', ...readdirSync(root)
    .filter(name => /^00[1-9]-.*\.sql$|^010-.*\.sql$/.test(name)).sort()];
  return '-- GENERATED by cloudflare/staging/build-schema.mjs; do not edit manually.\n' +
    '-- ONLY for a NEW, EMPTY actero-staging-db after explicit approval.\n' +
    '-- Includes baseline and historical migrations 001-010; do not apply them again.\n' +
    '-- No customer data, guide content, approvals or secrets are included.\n' +
    '-- Freeze this migration after first remote application; add new numbered migrations.\n\n' +
    sources.map(name => '-- Source: cloudflare/' + name + '\n' + readFileSync(new URL(name, root), 'utf8').trim() + '\n').join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length !== 1 || !['--write', '--check'].includes(args[0])) {
    throw new Error('Usage: node cloudflare/staging/build-schema.mjs --write|--check (offline only)');
  }
  const sql = buildSchema();
  if (args[0] === '--write') {
    mkdirSync(new URL('./migrations/', import.meta.url), {recursive: true});
    writeFileSync(schemaURL, sql);
    console.log('Prepared empty staging schema locally; no database was contacted.');
  } else {
    if (readFileSync(schemaURL, 'utf8') !== sql) throw new Error('Staging bootstrap drift: review source changes before regenerating.');
    console.log('Staging bootstrap matches baseline and migrations 001-010.');
  }
}
